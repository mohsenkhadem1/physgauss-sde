"""Public Stage-A factorization and development/train scene construction.

No reserved scenes are generated by this module's CLI. Actual test sampling
requires a later frozen protocol. Geometry families share a mapped-cuboid
topology; this is not arbitrary topology generalization.
"""
from dataclasses import asdict
import itertools
import numpy as np
import torch
from scripts.compositional_neural_mechanics.mechanics import GeometrySpec,AttachmentSpec,Q2Mechanics
from scripts.compositional_neural_mechanics.materials import teacher_energy
from scripts.compositional_neural_mechanics.interfaces import AnalyticInterfaceLaw

TRAIN_GEOMETRIES=(GeometrySpec((.20,.08,.08)),GeometrySpec((.24,.07,.08),.25,0.),GeometrySpec((.20,.08,.07),0.,.012))
NOVEL_GEOMETRIES=(GeometrySpec((.18,.09,.07),-.20,.009),GeometrySpec((.27,.065,.09),.18,-.008))


def split_cells():
    all_cells=list(itertools.product(range(3),range(2),range(2),range(2)))
    held=[(g,m,(g+m)%2,g%2) for g in range(3) for m in range(2)]
    return dict(train=[c for c in all_cells if c not in held],held_composition=held)


def poses(geometry):
    L,H,D=geometry.dimensions;actions={}
    p=np.zeros((2,6));p[0,0]=-.0025*L;p[1,0]=.0025*L;actions['initial']=p
    p=np.zeros((2,6));p[0,0]=-.12*L;p[1,0]=.12*L;actions['stretch']=p
    p=np.zeros((2,6));p[0,3]=-.45;p[1,3]=.45;actions['opposed_twist']=p
    p=np.zeros((2,6));p[1,5]=.45;actions['right_bend']=p
    p=np.zeros((2,6));p[0,1]=-.10*H;p[1,1]=.10*H;actions['opposed_shear']=p
    p=np.zeros((2,6));p[0,0]=-.06*L;p[1,0]=.06*L;p[0,5]=-.25;actions['stretch_bend']=p
    return actions


def sample_scene(cell,rng,name,*,geometry=None,gravity=(0.,0.,0.)):
    g,m,s,h=cell;geometry=geometry or TRAIN_GEOMETRIES[g]
    logscale=float(rng.uniform(-.4,.4));shape=float(rng.uniform(-.8,.8));gradient=float(rng.uniform(-.45,.45))
    E=11250.*np.exp(logscale);L,H,D=geometry.dimensions
    ratios=np.exp(rng.uniform(np.log(.3),np.log(5.),2));K=ratios*E*H*D/L
    centers=np.array([[.5,.25],[.5,.25 if s==0 else .75]])+rng.uniform(-.08,.08,(2,2))
    widths=np.exp(rng.uniform(np.log(.23),np.log(.40),(2,2)))
    # Both support-law families appear across continuous draws, independent of
    # the four combinatorial factors. The two ends may have different strengths.
    interface_family=int(rng.integers(2));strengths=rng.uniform(.2,.9,2)
    return dict(name=name,factors=dict(geometry=g,bulk=m,support=s,heterogeneity=h),geometry=asdict(geometry),
                bulk_family='mooney_rivlin' if m==0 else 'yeoh',
                bulk_latent=[logscale,shape,-1. if m==0 else 1.],gradient=gradient,
                interface_latents=[[float(np.log(k)),float(c),float(interface_family)] for k,c in zip(K,strengths)],
                centers=centers.tolist(),widths=widths.tolist(),support_stiffness_ratios=ratios.tolist(),
                gravity=list(gravity),density_kg_m3=125.)


def material_field(scene,parameters=None):
    def field(q):
        z=q.new_tensor(scene['bulk_latent']) if parameters is None else parameters[:3]
        amplitude=q.new_tensor(scene['gradient']) if parameters is None else parameters[3]
        # Distinct material-coordinate patterns; no dependence on deformed xyz.
        phi=torch.cos(torch.pi*q[...,0]) if scene['factors']['heterogeneity']==0 else torch.cos(torch.pi*q[...,1])*torch.cos(torch.pi*q[...,2])
        return torch.stack([z[0]+amplitude*phi,z[1].expand_as(phi),z[2].expand_as(phi)],dim=-1)
    return field


def make_model(scene,*,n=2,order=3,device='cpu',bulk_law=None,interface_law=None,
               bulk_parameters=None,interface_parameters=None,geometry_parameters=None):
    geometry=GeometrySpec(**scene['geometry']);family=scene['bulk_family']
    energy=(lambda F,z:teacher_energy(F,z[...,:2],family)) if bulk_law is None else bulk_law.energy_density
    law=AnalyticInterfaceLaw() if interface_law is None else interface_law
    attachments=tuple(AttachmentSpec(float(np.exp(z[0])),tuple(c),tuple(w)) for z,c,w in zip(scene['interface_latents'],scene['centers'],scene['widths']))
    fields=[]
    for side in range(2):
        def field(q,side=side):
            z=q.new_tensor(scene['interface_latents'][side]) if interface_parameters is None else interface_parameters[side]
            return z.expand(*q.shape[:-1],3)
        fields.append(field)
    return Q2Mechanics(geometry,n=n,order=order,bulk_energy=energy,material_latent_field=material_field(scene,bulk_parameters),
                       attachments=attachments,gravity=scene['gravity'],density=scene['density_kg_m3'],device=device,
                       interface_energy=law.energy_density,interface_latent_fields=fields,
                       interface_geometry_parameters=geometry_parameters)
