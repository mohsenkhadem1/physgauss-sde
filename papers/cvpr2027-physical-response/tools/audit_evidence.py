"""Audit saved result arithmetic and frozen report hashes; never read raw targets.

Run from any directory with Python3 (standard library only). This is an
independent publication audit, not a rerun of prediction or physical simulation.
The source hash manifest is deliberately not regenerated by this command.
"""
from pathlib import Path
import hashlib
import json
import statistics

HERE = Path(__file__).resolve().parents[1]
ROOT = HERE.parents[1]

def read(path):
    return json.loads((ROOT / path).read_text())

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def main():
    checks = []
    def check(label, condition):
        if not condition:
            raise AssertionError(label)
        checks.append(label)
    def close(label, observed, expected):
        check(label, abs(observed - expected) < 1e-9)
    manifest = json.loads((HERE / 'evidence/source-hashes.json').read_text())
    for path, expected in manifest['sha256'].items():
        check('hash: ' + path, sha(ROOT / path) == expected)
    physical = read('reports/complex-scenes-v18/held-physical-summary.json')
    rows = read(physical['source_report'])['rows']
    appearance = read('reports/complex-scenes-v18/held-appearance-summary.json')
    image_rows = read(appearance['source_report'])['rows']
    simulation = {}
    for method in ['ours', 'analytic-control', 'phystwin', 'spring-gaus']:
        subset = [r for r in rows if r['method'] == method]
        check('simulation48 complete: '+method, len(subset) == 48 and all(r['state'] == 'complete' for r in subset))
        check('simulation24 worlds: '+method, len({r['world_id'] for r in subset}) == 24)
        values = {
            'mean_motion_rms_mm': statistics.mean(r['metrics']['vector_rms_mm'] for r in subset),
            'mean_shape_rms_mm': statistics.mean(r['metrics']['rigid_aligned_shape_rms_mm'] for r in subset),
            'mean_net_impulse_rms_Ns': statistics.mean(r['impulse']['net_nongravitational_impulse_rms_Ns'] for r in subset),
        }
        for key, value in values.items():
            close(method+': '+key, value, physical['method_summary'][method][key])
        ir = [r for r in image_rows if r['method'] == method]
        check('appearance48 complete: '+method, len(ir) == 48 and all(r['state'] == 'complete' for r in ir))
        for key, expected in appearance['method_summary'][method]['completed_query_means'].items():
            close(method+': '+key, statistics.mean(r['metrics'][key] for r in ir), expected)
        values['foreground_psnr_db'] = statistics.mean(r['metrics']['psnr_foreground_union_db'] for r in ir)
        simulation[method] = values
    soft = read('reports/benchmark-improvement-v14/softvt-summary-b.json')['groups']['prospective_softvt_phase_b']
    check('SoftVT exact complete coverage', soft['proposed_coverage'] == dict(cases=40, complete_cases=40, total_frames=1998, failed_frames=0))
    soft_values = {}
    for key in ['contact_scene_state', 'rigid_scene_state', 'prefix_calibrated_rigid']:
        group = soft[key]; rr = group['per_case']
        check('SoftVT40 complete pairs '+key, len(rr)==40 and all(r['complete_pair'] for r in rr))
        close('SoftVT proposal mean '+key, statistics.mean(r['proposal_mm'] for r in rr), group['proposal_mean_mm'])
        close('SoftVT baseline mean '+key, statistics.mean(r['baseline_mm'] for r in rr), group['baseline_mean_mm'])
        soft_values[key] = {'ours_mm': group['proposal_mean_mm'], 'baseline_mm': group['baseline_mean_mm'], 'wins': sum(r['proposal_mm'] < r['baseline_mm'] for r in rr)}
    check('SoftVT36/40 mechanics wins', soft_values['contact_scene_state']['wins']==36)
    check('SoftVT35/40 rigid-contact wins', soft_values['rigid_scene_state']['wins']==35)
    real = read('reports/real-transfer-v22/scores.json')
    check('Real eight sequences', len(real['rows']) == 8)
    for method, summary in real['summary'].items():
        for metric in ['tracking_mm','displacement_mm','pair_distance_change_mm']:
            close('Real '+method+' '+metric, statistics.mean(r['results'][method]['manual'][metric] for r in real['rows']), summary[metric])
    real_render = read('reports/real-transfer-v22/summary.json')
    check('Real rendering eight sequences', len(real_render['per_case'])==8)
    for method, summary in real_render['render'].items():
        for metric, expected in summary.items():
            close('Real render '+method+' '+metric, statistics.mean(r['render'][method][metric] for r in real_render['per_case']), expected)
    transfer = read('reports/real-transfer-v22/transfer-scores.json')
    passed = [r for r in transfer['rows'] if r['registration']['initial_geometry_gate']]
    check('Real transfer2of5 gate', len(transfer['rows'])==5 and len(passed)==2)
    for group, subset in [('initial_geometry_gate_passed',passed),('all_five_diagnostic',transfer['rows'])]:
        for method, summary in transfer['summary'][group].items():
            for metric in ['tracking_mm','displacement_mm','pair_distance_change_mm']:
                close('Transfer '+group+' '+method+' '+metric, statistics.mean(r['results'][method]['whole_interaction'][metric] for r in subset), summary[metric])
    check('Real transfer mixed outcomes',sum(r['results']['neural']['whole_interaction']['tracking_mm'] < r['results']['native_frozen']['whole_interaction']['tracking_mm'] for r in passed)==1)
    observation = read('reports/compositional-neural-mechanics-v16/unknown-action-reaction-paper-summary.json')
    obs = {r['policy']:r for r in observation['rows'] if r['model']=='shared_laws_fitted'}
    check('Adaptive observation ties fixed stretch', observation['adaptive_equals_fixed_stretch'])
    check('Observation48 fits/41 converged', observation['fit_counts'] == dict(expected=48,present=48,optimizer_success=41,incomplete=7))
    ambiguity=read('reports/compositional-neural-mechanics-v16/appearance-physical-ambiguity.json')
    check('Scale example image identity',ambiguity['images_bit_identical'] and ambiguity['stiffness_multiplier']==2)
    close('Scale example double reaction',ambiguity['reaction_norms_N'][1],2*ambiguity['reaction_norms_N'][0])
    bridge=read('reports/compositional-neural-mechanics-v16/visual-bridge-development-results.json')['scale_ambiguity']
    check('Three-view scale control identities', bridge['images_bit_identical'] and len(bridge['views'])==3 and all(v['rgb_global_rmse']==0 for v in bridge['views'].values()))
    check('Three-view reaction scale', bridge['common_stiffness_multiplier']==2 and bridge['force_scaling_max_abs_error_N']<1e-12)
    check('Three-view residual matches main', abs(bridge['same_equilibrium_scaled_residual_N']-4.85e-13)<1e-15)
    # These token checks bind core numerical claims to the current manuscript.
    # They do not certify the full prose, architecture or literature review.
    tex=(HERE/'main.tex').read_text()
    tokens=['1.97','10.80','11.27','1.84','17.865','18.543','18.932','39.16','44.63','39.01','21.14','16.13','17.66','0.3395','0.0802','0.0961','0.0292']
    for token in tokens:
        check('Main numerical token '+token,token in tex)
    result={
        'passed':True,'checks':checks,'number_of_checks':len(checks),
        'source_manifest_sha256':sha(HERE/'evidence/source-hashes.json'),
        'main_tex_sha256':sha(HERE/'main.tex'),
        'recomputed':{'simulation':simulation,'softvt':soft_values,'real':real['summary'],'real_transfer':transfer['summary'],'additional_observation':{k:obs[k] for k in ['initial','fixed_stretch']}},
        'scope':'Saved report hashes and scalar arithmetic; no raw target reads, refitting, simulation or independent physical-ground-truth validation. Main numerical token presence is not full semantic certification.',
        'limitations':['Distinct adapters/protocols; no pooled performance.','Analytic control is best simulation aggregate.','Real native continuation wins; real transfer is a mixed two-pair pilot.','Uncertainty is not calibrated; active selection ties fixed action.','PDF layout and citation accuracy require separate review.'],
    }
    (HERE/'evidence/current-audit.json').write_text(json.dumps(result,indent=2)+'\n')
    print('PASS',len(checks),'evidence checks; wrote evidence/current-audit.json')

if __name__=='__main__':
    main()
