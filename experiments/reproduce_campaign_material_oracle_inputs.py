"""Regenerate local oracle inputs from published recipes, never overwrite data.

The frozen design/protocol JSONs are small public evidence. Raw meshes,
hypotheses and command archives remain local and are reconstructed here from
their generators; every generated byte string must match its published hash.
No response trajectory, observation or physical simulation is read or run.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
from pathlib import Path
import numpy as np

try:
    from campaign_hypothesis_inputs import public_hardware_contexts,make_manifest,make_prior,plain
    from campaign_material_marginal import MaterialMarginalPrior,realize_known_support_material
    from campaign_exciting_commands import PROGRAM_IDS,make_exciting_commands
    from campaign_sparse_depth_queries import make_queries
except ImportError:
    from experiments.campaign_hypothesis_inputs import public_hardware_contexts,make_manifest,make_prior,plain
    from experiments.campaign_material_marginal import MaterialMarginalPrior,realize_known_support_material
    from experiments.campaign_exciting_commands import PROGRAM_IDS,make_exciting_commands
    from experiments.campaign_sparse_depth_queries import make_queries

ROOT = Path(__file__).resolve().parents[1]


def json_bytes(value):
    return (json.dumps(plain(value),indent=2,allow_nan=False)+'\n').encode()


def reproduce(design_path,*,verify=False):
    design = json.loads(Path(design_path).read_text())
    checked = []
    def ensure(record,data):
        path = (ROOT/record['path']).resolve()
        if not path.is_relative_to(ROOT) or hashlib.sha256(data).hexdigest()!=record['sha256']:
            raise ValueError('Generated bytes differ from the frozen recipe: '+record['path'])
        if path.exists():
            if path.read_bytes()!=data:
                raise ValueError('Existing input differs; refusing to overwrite: '+record['path'])
        elif verify:
            raise ValueError('Local input missing: '+record['path'])
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_bytes(data)
        checked.append(record['path'])

    public = public_hardware_contexts()[0]
    ensure(design['public_hardware'],json_bytes(public))
    cohort = make_manifest(program_ids=list(PROGRAM_IDS),seed=20261022)
    template = next(h['spec'] for h in cohort['hypotheses'] if h['id']=='H0__m0__bc0')
    ensure(design['nominal_support_template'],json_bytes(template))
    prior = MaterialMarginalPrior(make_prior(public))
    if prior.metadata()!=design['material_prior']:
        raise ValueError('Published marginal prior differs')
    state = prior.sample(1,np.random.default_rng(design['truth_seed']))
    spec = realize_known_support_material(public,template,state)[0]
    ensure(design['truth_spec'],json_bytes(spec))
    rest,faces = np.array(public['rest_points_m']),np.array(public['surface_faces'])
    acquired = make_queries(rest,faces,frame_indices=(10,20),offsets_deg=((0.,0.),),grid_size=6)
    held = make_queries(rest,faces,frame_indices=(30,50),offsets_deg=((60.,10.),),grid_size=6)
    ensure(design['public_acquired_queries'],json_bytes(acquired))
    ensure(design['public_held_queries'],json_bytes(held))
    for record in design['physics_cases']:
        path = ROOT/record['path']
        if hashlib.sha256(path.read_bytes()).hexdigest()!=record['sha256']:
            raise ValueError('Published finite protocol changed')
        protocol = json.loads(path.read_text())
        clock = make_exciting_commands(protocol['program_id'])
        archive = io.BytesIO()
        np.savez_compressed(archive,**{k:getattr(clock,k) for k in [
            'endpoint_times_s','output_times_s','handle_forces_world_N',
            'handle_torques_world_Nm','nodal_forces_world_N','body_acceleration_world_m_s2']})
        ensure(protocol['known_commands'],archive.getvalue())
    return dict(verified=checked,writes_allowed=not verify,physics_runs=0,response_reads=0)


if __name__=='__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--design',default='runs/operator-dev/material-oracle-depth-v01/protocol-design.json')
    parser.add_argument('--verify',action='store_true')
    args = parser.parse_args()
    print(json.dumps(reproduce(args.design,verify=args.verify)))
